const assert = require('node:assert/strict');
const {arc,features,bounds} = require('../Ares/Resources/Routing/routing-geometry.js');
const crossing=arc([170,30],[-175,40]);
assert.ok(crossing.every((p,i)=>i===0||Math.abs(p[0]-crossing[i-1][0])<180));
const box=bounds(crossing);
assert.ok(box[1][0]-box[0][0]<20);
const route=i=>({id:String(i),endpoints:[{location:{longitude:170,latitude:30}},{location:null},{location:{longitude:-175,latitude:40}}]});
const full=features(Array.from({length:20000},(_,i)=>route(i)));
assert.equal(full.lines.features.length,1);
assert.equal(full.points.features.length,2);
assert.equal(full.memberships.get(full.lines.features[0].properties.key).length,20000);
const huge=Array.from({length:300000},(_,i)=>[i%360-180,i%170-85]);
assert.ok(bounds(huge).flat().every(Number.isFinite));
assert.equal(bounds([]),null);
assert.equal(features([{id:'unknown',endpoints:[{location:null}]}]).points.features.length,0);
for(const pair of [[[0,0],[0,0]],[[0,0],[180,0]],[[179,85],[-179,-85]]]) assert.ok(arc(...pair).flat().every(Number.isFinite));
console.log('Routing geometry: antimeridian, 20,000 memberships, 300,000 bounds points, unknown and degenerate coordinates passed.');
const {splitDateLine} = require('../Ares/Resources/Routing/routing-geometry.js');
const split=splitDateLine(crossing);
assert.equal(split.length,2);
assert.ok(split.every(segment=>segment.every((p,i)=>i===0||Math.abs(p[0]-segment[i-1][0])<=180)));
assert.equal(full.lines.features[0].geometry.type,'MultiLineString');
console.log('Date-line splitting preserves both world-map segments.');
